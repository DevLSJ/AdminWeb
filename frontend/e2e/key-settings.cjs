// Disposable local servers only: creates sample keys and changes settings.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
(async () => {
  const base = process.env.SETTINGS_E2E_URL || 'http://127.0.0.1:5189';
  const api = process.env.SETTINGS_E2E_API || 'http://127.0.0.1:18089';
  for (const url of [base, api]) assert(['localhost', '127.0.0.1'].includes(new URL(url).hostname), 'Use a disposable local environment');
  const password = process.env.SETTINGS_E2E_PASSWORD;
  assert(password, 'Set SETTINGS_E2E_PASSWORD for sample admin/dguard accounts');
  const output = process.env.SETTINGS_E2E_OUTPUT || '/tmp/key-settings-browser';
  await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_EXECUTABLE || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: 'Asia/Seoul' });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const checks = []; const pass = label => { checks.push(label); console.log('PASS: ' + label); };
  const wait = async predicate => { for (let i = 0; i < 60; i++) { if (await predicate()) return; await new Promise(resolve => setTimeout(resolve, 100)); } throw Error('Condition timed out'); };
  const login = async (p, id) => { await p.goto(base + '/login'); await p.getByLabel('아이디').fill(id); await p.getByLabel('비밀번호').fill(password); await p.getByRole('button', { name: '로그인', exact: true }).click(); await p.waitForURL(base + '/'); };
  try {
    await login(page, 'admin');
    const token = await page.evaluate(() => localStorage.getItem('token'));
    const request = async (path, method = 'GET', body, expected = 200) => {
      const r = await page.request.fetch(api + path, { method, headers: { Authorization: 'Bearer ' + token }, ...(body ? { data: body } : {}) });
      assert.equal(r.status(), expected, `${method} ${path}: ${await r.text()}`); return (await r.json()).data;
    };
    let policy = await request('/api/settings/key-policy');
    // Reset only the disposable environment's settings to make reruns deterministic.
    await request('/api/settings/key-policy', 'PUT', { defaultValidityDays: 365, expiryWarningDays: 30, version: policy.version, reason: '시연 초기 정책' });
    let codes = await request('/api/settings/key-codes');
    let rsa = codes.find(c => c.group === 'ALGORITHM' && c.code === 'RSA');
    if (!rsa.enabled) await request('/api/settings/key-codes/ALGORITHM/RSA', 'PATCH', { ...rsa, enabled: true, reason: '시연 초기 코드' });
    policy = await request('/api/settings/key-policy');
    const addDays = days => { const d = new Date(policy.today + 'T00:00:00Z'); d.setUTCDate(d.getUTCDate() + days); return d.toISOString().slice(0, 10); };
    const prefix = '설정시연-' + Date.now();
    const create = async (label, days, status = 'ACTIVE') => {
      const k = await request('/api/keys', 'POST', { keyName: prefix + '-' + label, algorithm: 'AES', keySize: 256, purpose: 'ENCRYPT', expireAt: addDays(days) });
      await request(`/api/keys/${k.keyUid}/status`, 'PATCH', { toStatus: 'ACTIVE', reason: '격리 환경 UI 시연' });
      if (status !== 'ACTIVE') await request(`/api/keys/${k.keyUid}/status`, 'PATCH', { toStatus: status, reason: '격리 환경 상태 시연' });
      return k;
    };
    const soon = await create('5일후', 5), twenty = await create('20일후', 20), far = await create('40일후', 40), compromised = await create('침해', 5, 'COMPROMISED'), destroyed = await create('폐기', 5, 'DESTROYED');
    await page.goto(base + '/keys?keyword=' + encodeURIComponent(prefix));
    const row = key => page.getByRole('row').filter({ hasText: key.keyName });
    await row(soon).waitFor();
    assert.equal(await row(soon).getAttribute('data-expiring'), 'true');
    assert.equal(await row(twenty).getAttribute('data-expiring'), 'true');
    for (const key of [far, compromised, destroyed]) assert.equal(await row(key).getAttribute('data-expiring'), null);
    assert.notEqual(await row(soon).evaluate(e => getComputedStyle(e).backgroundColor), 'rgba(0, 0, 0, 0)');
    assert.equal(await row(destroyed).locator('[data-testid="DeleteForeverRoundedIcon"]').count(), 1);
    assert.equal(await row(compromised).locator('[data-testid="DeleteForeverRoundedIcon"]').count(), 0);
    await page.screenshot({ path: output + '/keys-warning-and-destroyed.png', fullPage: true });
    pass('만료 임박 행 배경 및 폐기 전용 아이콘');
    const dialog = page.getByRole('dialog', { name: '새 암호 키 등록' });
    const openRegister = async () => { await page.getByRole('button', { name: '키 등록', exact: true }).click(); await wait(() => dialog.getByLabel('키 이름').isEnabled()); };
    const cancel = () => dialog.getByRole('button', { name: '취소', exact: true }).click();
    await openRegister();
    const system = new Date(), month = `${system.getFullYear()}년 ${system.getMonth() + 1}월`;
    assert(await dialog.getByText(month, { exact: true }).isVisible());
    assert(await dialog.getByText(policy.defaultExpireAt, { exact: true }).isVisible());
    await page.screenshot({ path: output + '/registration-current-month.png', fullPage: true });
    await dialog.getByRole('button', { name: '1년 후', exact: true }).click();
    assert(await dialog.getByText(`${system.getFullYear() + 1}년 ${system.getMonth() + 1}월`, { exact: true }).isVisible());
    await cancel(); await openRegister(); assert(await dialog.getByText(month, { exact: true }).isVisible()); await cancel();
    const next = new Date(system.getFullYear(), system.getMonth() + 1, 1, 12);
    await page.clock.setFixedTime(next); await openRegister();
    assert(await dialog.getByText(`${next.getFullYear()}년 ${next.getMonth() + 1}월`, { exact: true }).isVisible());
    await cancel(); await page.clock.setFixedTime(system);
    pass('현재 월·재열기·시스템 다음 달과 기존 날짜 바로가기');
    await page.goto(base + '/settings');
    await page.getByLabel('기본 유효기간(일)').fill('90');
    await page.getByLabel('만료 알림일(만료 전 일수)').fill('7');
    await page.getByLabel('정책 변경 사유').fill('브라우저 정책 반영 시연');
    await page.getByRole('button', { name: '정책 저장', exact: true }).click();
    await page.getByText('설정을 저장했습니다.', { exact: true }).waitFor();
    assert.equal((await request('/api/settings/key-policy')).defaultValidityDays, 90);
    assert.equal((await request(`/api/keys/${soon.keyUid}`)).expireAt, soon.expireAt);
    await page.screenshot({ path: output + '/settings-policy.png', fullPage: true });
    await page.goto(base + '/keys?keyword=' + encodeURIComponent(prefix)); await row(soon).waitFor();
    await wait(async () => await row(twenty).getAttribute('data-expiring') === null);
    assert.equal(await row(soon).getAttribute('data-expiring'), 'true');
    await openRegister(); assert(await dialog.getByText(addDays(90), { exact: true }).isVisible());
    await dialog.getByLabel('키 이름').fill(prefix + '-정책90일');
    await dialog.getByRole('button', { name: '키 생성 및 v1 반영', exact: true }).click();
    await dialog.getByText(prefix + '-정책90일 등록 완료', { exact: true }).waitFor();
    await dialog.getByRole('button', { name: '완료', exact: true }).click();
    pass('정책 저장·기존 만료일 보존·7일 경고·90일 기본값으로 실제 등록');
    await page.goto(base + '/settings');
    await page.getByRole('row').filter({ has: page.getByRole('cell', { name: 'RSA', exact: true }) }).getByRole('button', { name: '수정' }).click();
    const edit = page.getByRole('dialog');
    await edit.getByRole('switch').uncheck();
    await edit.getByLabel('코드 변경 사유').fill('RSA 신규 생성 일시 중지');
    await edit.getByRole('button', { name: '저장', exact: true }).click(); await edit.waitFor({ state: 'hidden' });
    await request('/api/keys', 'POST', { keyName: prefix + '-차단', algorithm: 'RSA', keySize: 2048, purpose: 'ENCRYPT' }, 400);
    await page.goto(base + '/keys'); await openRegister(); await dialog.getByRole('combobox').first().click();
    assert.equal(await page.getByRole('option', { name: '공개키 · RSA-2048-SHA256', exact: true }).getAttribute('aria-disabled'), 'true');
    await page.keyboard.press('Escape'); await cancel();
    assert.equal((await request('/api/audit-logs/verify')).valid, true);
    pass('알고리즘 신규 생성 중지 화면·API 및 감사 체인');
    const other = await browser.newContext({ viewport: { width: 1440, height: 1000 } }); const admin = await other.newPage();
    await login(admin, 'dguard'); await admin.goto(base + '/settings'); await admin.getByLabel('기본 유효기간(일)').waitFor();
    assert(await admin.getByLabel('기본 유효기간(일)').isDisabled());
    assert.equal(await admin.getByRole('button', { name: '정책 저장', exact: true }).count(), 0);
    await other.close(); pass('일반 ADMIN 조회 전용 화면');
    assert.deepEqual(errors, []); await fs.writeFile(output + '/result.json', JSON.stringify({ checks, errors }, null, 2));
  } catch (error) { await page.screenshot({ path: output + '/failure.png', fullPage: true }); throw error; }
  finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
